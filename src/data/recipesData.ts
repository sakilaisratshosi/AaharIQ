function deriveDifficulty(recipe: RawRecipe): { en: 'Easy' | 'Medium' | 'Hard'; bn: string } {
  const explicit = recipe.difficulty;
  if (explicit) {
    return {
      en: explicit,
      bn: explicit === 'Easy' ? 'সহজ' : explicit === 'Hard' ? 'কঠিন' : 'মাঝারি',
    };
  }
  const totalMins = (recipe.prepTime || 0) + (recipe.cookTime || 0);
  if (totalMins <= 30 && recipe.instructions.length <= 5) {
    return { en: 'Easy', bn: 'সহজ' };
  }
  if (totalMins >= 60 || recipe.instructions.length >= 6) {
    return { en: 'Medium', bn: 'মাঝারি' };
  }
  return { en: 'Medium', bn: 'মাঝারি' };
}

function estimateSugarFromIngredients(recipe: RawRecipe): number {
  if (typeof recipe.sugarPerServing === 'number') return recipe.sugarPerServing;
  const hay = `${recipe.name} ${recipe.ingredients.map((i) => i.name).join(' ')}`.toLowerCase();
  if (hay.includes('jaggery') || hay.includes('gur') || hay.includes('sugar') || hay.includes('honey') || hay.includes('glaze') || hay.includes('teriyaki')) {
    return 14;
  }
  if (hay.includes('tomato') || hay.includes('carrot') || hay.includes('pumpkin') || hay.includes('sweet potato')) {
    return 4.5;
  }
  return 2.5;
}

